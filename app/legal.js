/* ⊗ AICS — legal document generators (pure functions, no DOM)
 * Templates only: they are starting points to review with counsel, not legal advice.
 * Loads in the browser as window.AICSLegal and in Node via require().
 */
(function (root, factory) {
  var api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.AICSLegal = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function today(now) { return new Date(now || Date.now()).toISOString().slice(0, 10); }
  function usd(n) { return '$' + Number(n || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 }); }
  var DISCLAIMER = 'TEMPLATE — generated by AI Copyright Shield. Not legal advice; review with counsel before use.';

  function tosAddendum(cfg, now) {
    var licensed = (cfg.licensed || []).length ? cfg.licensed.join(', ') : 'none';
    return [
      DISCLAIMER, '',
      'AI USAGE ADDENDUM TO THE TERMS OF SERVICE OF ' + cfg.owner.toUpperCase(),
      'Effective ' + today(now) + ' · Licence ID ' + cfg.id, '',
      '1. Reservation of rights.',
      '   All content on this site is protected by copyright. The owner expressly reserves',
      '   text-and-data-mining rights (EU Directive 2019/790, Art. 4(3)) through machine-readable',
      '   means: robots.txt, /ai.txt, /.well-known/tdmrep.json, "noai" meta tags and HTTP headers.', '',
      '2. Restricted uses.',
      '   Without a paid AICS licence you may not use site content to train, fine-tune or evaluate',
      '   machine-learning models; include it in datasets; embed or index it in vector stores; or',
      '   retrieve, summarise or reproduce it in AI-generated output.', '',
      '3. Licensed access.',
      '   Licences are issued per crawler. Licensed crawlers authenticate with the header',
      '   "Authorization: AICS-License <key>" and are metered at ' + cfg.rate + ' USD per token',
      '   delivered (tokens estimated as characters / 4). Current licensees: ' + licensed + '.', '',
      '4. Unlicensed access.',
      '   Requests from AI crawlers without a valid licence are refused (HTTP 402) and logged.',
      '   Any content obtained without a licence is chargeable at the published rate, and the owner',
      '   may pursue all remedies available under applicable copyright law.', '',
      '5. Records.',
      '   Access logs (crawler identity, time, pages, token counts) are kept as evidence of use',
      '   and form the basis of invoices.', '',
      '6. Contact.',
      '   Licence requests and disputes: see ' + (cfg.termsURL || '/ai.txt') + '.'
    ].join('\n');
  }

  function unlicensedNotice(cfg, vendor, usage, now) {
    usage = usage || {};
    var blocked = usage.blocked || { events: 0, pages: 0, tokens: 0, amount: 0 };
    var billed = usage.billed || { events: 0, pages: 0, tokens: 0, amount: 0 };
    return [
      DISCLAIMER, '',
      today(now), '',
      'To: ' + vendor + ' — legal / data acquisition team',
      'From: ' + cfg.owner + ' (AI Copyright Shield licence ' + cfg.id + ')',
      'Re: Unlicensed AI crawling of ' + cfg.owner + (usage.period ? ' — ' + usage.period : ''), '',
      'Our records show crawlers operated by ' + vendor + ' (' + ((usage.bots || []).join(', ') || 'identified by user agent') + ')',
      'requested content from our site without an AI licence:', '',
      '  Unlicensed requests:   ' + blocked.events + ' (' + blocked.pages + ' pages, ~' + blocked.tokens.toLocaleString('en-US') + ' tokens)',
      '  Charge at published rate (' + cfg.rate + ' USD/token): ' + usd(blocked.amount),
      billed.events ? '  Licensed, metered requests: ' + billed.events + ' (' + usd(billed.amount) + ', invoiced separately)' : '',
      '',
      'Our site reserves text-and-data-mining rights in machine-readable form (robots.txt, ai.txt,',
      'TDMRep and "noai" signals). We ask that you:', '',
      '  1. stop crawling the site for AI purposes unless you hold an AICS licence key;',
      '  2. confirm whether content already collected has been used for training or retrieval;',
      '  3. either obtain a licence for continued access or settle the charge above within 30 days.', '',
      'Licence terms and authentication details: ' + (cfg.termsURL || '/ai.txt') + '.', '',
      'Sincerely,', cfg.owner
    ].filter(function (l, i, a) { return l !== '' || a[i - 1] !== ''; }).join('\n');
  }

  return { tosAddendum: tosAddendum, unlicensedNotice: unlicensedNotice, DISCLAIMER: DISCLAIMER };
});
